/// Sorts text from any source (clipboard, URL scheme, drag and drop) into
/// MEGA links, which open at once, and link-protector links, which go to Bypass.
nonisolated enum LinkSorter {
    struct Result: Sendable {
        var mega: [String] = []
        var protected: [String] = []
        var isEmpty: Bool { mega.isEmpty && protected.isEmpty }

        mutating func add(_ other: Result) {
            for link in other.mega where !mega.contains(link) { mega.append(link) }
            for link in other.protected where !protected.contains(link) { protected.append(link) }
        }
    }

    private static let urlPattern = try! NSRegularExpression(pattern: #"https?://[^\s"'<>]+"#, options: [.caseInsensitive])

    /// - Parameter protectorHosts: hosts that count as link protectors (the user can edit them).
    /// - Parameter allWebLinks: send every non-MEGA web link to Bypass (for explicit bypass requests).
    static func sort(_ text: String, protectorHosts: Set<String>, allWebLinks: Bool = false) -> Result {
        var result = Result()
        result.mega = LinkParser.links(in: text).map(\.0)
        let range = NSRange(text.startIndex..., in: text)
        var seen = Set<String>()
        for match in urlPattern.matches(in: text, range: range) {
            guard let range = Range(match.range, in: text) else { continue }
            let link = String(text[range]).trimmingCharacters(in: CharacterSet(charactersIn: ".,;)]}>"))
            guard let url = URL(string: link), let host = url.host()?.lowercased(), !isMega(host),
                  seen.insert(link).inserted else { continue }
            if allWebLinks || (matches(host, protectorHosts) && isLocker(url)) {
                result.protected.append(link)
            }
        }
        return result
    }

    /// One address from another app: a mega:// link, or a web link when MegaGlass is the
    /// default browser. Only the address itself counts, not links in its query, and a
    /// mega:// address never goes to Bypass.
    static func incoming(_ url: URL, protectorHosts: Set<String>) -> Result {
        var result = Result()
        switch url.scheme?.lowercased() {
        case "mega":
            result.mega = LinkParser.links(in: url.absoluteString).prefix(1).map(\.0)
        case "http", "https":
            guard let host = url.host()?.lowercased() else { break }
            if isMega(host) {
                result.mega = LinkParser.links(in: url.absoluteString).prefix(1).map(\.0)
            } else if matches(host, protectorHosts), isLocker(url) {
                result.protected = [url.absoluteString]
            }
        default:
            break
        }
        return result
    }

    /// The home page and the account, login and password pages of a protector site are
    /// not links to bypass: their addresses can hold tokens.
    static func isLocker(_ url: URL) -> Bool {
        let parts = url.pathComponents.filter { $0 != "/" }.map { $0.lowercased() }
        return !parts.isEmpty && !parts.contains(where: accountPages.contains)
    }

    private static let accountPages: Set<String> = [
        "login", "logout", "signin", "sign-in", "signup", "sign-up", "register", "auth", "oauth",
        "account", "accounts", "dashboard", "settings", "profile", "password", "reset-password",
        "forgot-password", "verify", "admin", "api",
    ]

    static func isMega(_ host: String) -> Bool {
        ["mega.nz", "mega.co.nz", "mega.app", "mega.io"].contains { host == $0 || host.hasSuffix("." + $0) }
    }

    static func matches(_ host: String, _ hosts: Set<String>) -> Bool {
        hosts.contains { host == $0 || host.hasSuffix("." + $0) }
    }

    static let defaultProtectorHosts: [String] = [
        "rapid-links.net", "speedy-links.com", "best-links.org", "fast-links.org", "ultra-links.net",
        "free-content.pro", "free-leaks.com", "mdlinkshub.com", "link-direct.pro", "linkvertise.com",
        "link-to.net", "link-center.net", "link-hub.net", "link-target.net", "direct-link.net",
        "file-link.net", "up-to-down.net", "loot-link.com", "lootdest.org", "lootdest.info",
        "lootlabs.gg", "links-loot.com", "loot-links.com", "work.ink", "workink.net", "ouo.io",
        "ouo.press", "shrinkme.io", "shrinkearn.com", "exe.io", "fc.lc", "adfoc.us", "sub2unlock.com",
        "sub2unlock.net", "rekonise.com", "mboost.me", "boost.ink", "bstlar.com", "lockr.so",
        "paster.so", "keeplinks.org", "linkshortify.com", "gplinks.co", "shrtco.de", "adshnk.com",
        "social-unlock.com",
    ]
}

/// Markers of nspasteboard.org: clipboard managers do not keep these items.
nonisolated extension NSPasteboard.PasteboardType {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}

/// Writes to the pasteboard and remembers the change, so the clipboard watch
/// does not act on the app's own copies. Links hold decryption keys: the copy stays on
/// this Mac (no Universal Clipboard) and out of clipboard histories.
enum Pasteboard {
    private(set) static var ownChangeCount = -1

    static func copy(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        pasteboard.setString(text, forType: .string)
        pasteboard.setString("", forType: .concealed)
        ownChangeCount = pasteboard.changeCount
    }
}

/// Opt-in: when you copy a MEGA or protector link anywhere, the app takes it.
/// Only the change counter is polled. After a change, macOS tells whether the copy holds a
/// web address, without the text and with no alert; only then is the text read. macOS
/// asks before each read, unless you allow MegaGlass in Paste from Other Apps.
@Observable
final class ClipboardWatcher {
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var check: Task<Void, Never>?
    /// The same text again soon after is the same copy (some apps write it twice).
    @ObservationIgnored private var last: (text: String, time: ContinuousClock.Instant)?
    @ObservationIgnored private var toldDenied = false
    @ObservationIgnored var onText: ((String) -> Void)?
    /// Once for each run: a copy came while macOS denies access to the clipboard.
    @ObservationIgnored var onDenied: (() -> Void)?

    var isRunning: Bool { timer != nil }

    func setEnabled(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        check?.cancel()
        check = nil
        guard enabled else { return }
        lastCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.3
    }

    /// Larger text is not a copied link.
    nonisolated private static let maxLength = 100_000

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard count != Pasteboard.ownChangeCount else { return }
        // Password managers and other apps mark secrets: they are not read.
        guard let types = pasteboard.types, types.contains(.string),
              !types.contains(where: { [.concealed, .transient, .autoGenerated].contains($0) }) else { return }
        guard pasteboard.accessBehavior != .alwaysDeny else {
            if !toldDenied {
                toldDenied = true
                onDenied?()
            }
            return
        }
        check?.cancel()
        check = Task {
            guard let text = await Self.copiedText(changeCount: count), !Task.isCancelled,
                  pasteboard.changeCount == count else { return }
            let now = ContinuousClock.now
            if let last, last.text == text, now - last.time < .seconds(2) { return }
            last = (text, now)
            onText?(text)
        }
    }

    /// The copied text, when macOS finds a web address in it: the whole text ("Paste and Go")
    /// or a part of it. macOS tells this without the text and with no alert. The text is read
    /// here, not on the main thread: a large copy takes time.
    @concurrent static func copiedText(from name: NSPasteboard.Name = .general, changeCount: Int) async -> String? {
        let pasteboard = NSPasteboard(name: name)
        guard let found = try? await pasteboard.detectedPatterns(for: [\.probableWebURL, \.links]), !found.isEmpty,
              pasteboard.changeCount == changeCount,
              let text = pasteboard.string(forType: .string), text.utf16.count <= maxLength else { return nil }
        return text
    }
}

/// Optional "default browser" mode, like magnet links for a torrent app: MEGA and
/// protector links from other apps come to MegaGlass; every other link goes on to
/// the real browser at once.
enum BrowserRouter {
    static var isDefaultBrowser: Bool {
        guard let handler = NSWorkspace.shared.urlForApplication(toOpen: URL(string: "https://example.com")!) else { return false }
        return Bundle(url: handler)?.bundleIdentifier == Bundle.main.bundleIdentifier
    }

    /// Installed browsers other than MegaGlass.
    static func browsers() -> [URL] {
        let own = Bundle.main.bundleIdentifier
        return NSWorkspace.shared.urlsForApplications(toOpen: URL(string: "https://example.com")!)
            .filter { isForwardTarget($0, ownBundleID: own) }
    }

    static func name(of app: URL) -> String {
        FileManager.default.displayName(atPath: app.path).replacingOccurrences(of: ".app", with: "")
    }

    /// The browser that gets non-MEGA links: the saved choice, else the current default
    /// browser, else the default browser before MegaGlass, else Safari. Never an
    /// unknown app that also opens web links.
    static func target(saved: String, previous: String) -> URL? {
        for path in [saved, previous] where !path.isEmpty {
            let candidate = URL(filePath: path)
            if isForwardTarget(candidate) { return candidate }
        }
        if let handler = defaultBrowser { return handler }
        return NSWorkspace.shared.urlForApplication(withBundleIdentifier: "com.apple.Safari")
    }

    /// The default browser when it is not MegaGlass.
    private static var defaultBrowser: URL? {
        NSWorkspace.shared.urlForApplication(toOpen: URL(string: "https://example.com")!).flatMap { isForwardTarget($0) ? $0 : nil }
    }

    /// Keeps the default browser while it is another app, for the time MegaGlass takes its place.
    static func rememberDefault(in settings: AppSettings) {
        if let handler = defaultBrowser, handler.path != settings.previousBrowser { settings.previousBrowser = handler.path }
    }

    static func isForwardTarget(_ app: URL, ownBundleID: String? = Bundle.main.bundleIdentifier) -> Bool {
        guard let identifier = Bundle(url: app)?.bundleIdentifier else { return false }
        return identifier != (ownBundleID ?? AppPaths.bundleID) && identifier != AppPaths.bundleID
    }

    static func forward(_ urls: [URL], settings: AppSettings) {
        guard !urls.isEmpty, let browser = target(saved: settings.forwardBrowser, previous: settings.previousBrowser) else { return }
        let configuration = NSWorkspace.OpenConfiguration()
        configuration.activates = true
        NSWorkspace.shared.open(urls, withApplicationAt: browser, configuration: configuration)
    }
}
